import type { Dependency, Font } from './collect.ts'

const copyrightLine = /^\s*(?:copyright\b|\(c\)|©)/iu

interface LicenseGroup {
	license: string
	body: string
	packages: { id: string; copyrights: string[] }[]
}

// Only the notices at the top belong to the package; later ones are part of the text (bundled licences).
const headerLines = 12

interface LicenseParts {
	copyrights: string[]
	body: string
}

function isHeaderCopyright(line: string, index: number): boolean {
	return index < headerLines && copyrightLine.test(line)
}

/** Splits a licence file into the copyright notices at its top and the rest of the text. */
export function splitLicense(text: string): LicenseParts {
	const lines = text.replaceAll('\r\n', '\n').split('\n')

	return {
		copyrights: lines
			.filter((line, index) => isHeaderCopyright(line, index))
			.map((line) => line.trim()),
		body: lines
			.filter((line, index) => !isHeaderCopyright(line, index))
			.join('\n')
			.trim()
			.replaceAll(/\n{3,}/gu, '\n\n'),
	}
}

/** Packages that share a licence's terms word for word share one copy of them. */
function groupByLicense(
	dependencies: Pick<Dependency, 'name' | 'version' | 'license' | 'licenseText'>[],
): LicenseGroup[] {
	const groups = new Map<string, LicenseGroup>()

	for (const dependency of dependencies) {
		const { copyrights, body } = splitLicense(dependency.licenseText ?? '')
		const key = `${dependency.license}\n${body.replaceAll(/\s+/gu, ' ')}`
		const group = groups.get(key) ?? { license: dependency.license, body, packages: [] }

		group.packages.push({ id: `${dependency.name}@${dependency.version}`, copyrights })
		groups.set(key, group)
	}

	return [...groups.values()].toSorted(
		(a, b) => a.license.localeCompare(b.license) || b.packages.length - a.packages.length,
	)
}

function fence(text: string): string {
	// A licence that itself contains a fence would end ours early; four backticks never appear in one.
	return ['````text', text, '````'].join('\n')
}

function renderGroup(group: LicenseGroup, index: number): string {
	const lines = [`### ${index + 1}. ${group.license}`, '']

	for (const { id, copyrights } of group.packages) {
		lines.push(`- \`${id}\`${copyrights.length > 0 ? `: ${copyrights.join('; ')}` : ''}`)
	}

	lines.push('', group.body === '' ? '_The package ships no licence file._' : fence(group.body), '')

	return lines.join('\n')
}

export function renderNotices(dependencies: Dependency[], fonts: Font[] = []): string {
	const notices = dependencies.filter(({ noticeText }) => noticeText !== null)

	return [
		'# Third-party notices',
		'',
		'stockpot includes the following packages: every run-time dependency of `packages/app` and',
		'`packages/ui`, transitively, and the fonts bundled in `packages/ui/src/fonts`. Each licence text',
		'appears once, after the packages and fonts it covers and their copyright notices; packages that ship',
		'a NOTICE file have it reproduced at the end.',
		'',
		'Generated by `bun run notices`. Do not edit by hand.',
		'',
		'## Packages',
		'',
		'| Package | Version | Licence |',
		'| --- | --- | --- |',
		...dependencies.map(
			({ name, version, license }) => `| \`${name}\` | ${version} | ${license} |`,
		),
		'',
		...(fonts.length > 0
			? [
					'## Fonts',
					'',
					'| Font | Version | Licence | Source |',
					'| --- | --- | --- | --- |',
					...fonts.map(
						({ name, version, license, source }) =>
							`| ${name} | ${version} | ${license} | <${source}> |`,
					),
					'',
				]
			: []),
		'## Licence texts',
		'',
		...groupByLicense([...dependencies, ...fonts]).map((group, index) => renderGroup(group, index)),
		...(notices.length > 0 ? ['## NOTICE files', ''] : []),
		...notices.flatMap(({ name, version, noticeText }) => [
			`### \`${name}@${version}\``,
			'',
			fence((noticeText ?? '').trim()),
			'',
		]),
	].join('\n')
}
